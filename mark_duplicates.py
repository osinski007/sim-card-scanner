lines = csv_data.strip().split('\n')

b_values = []
c_values = []

for line in lines:
    parts = line.strip().split(',')
    if len(parts) >= 4:
        b_values.append(parts[1])
        c_values.append(parts[2])

c_set = set(c_values)

for i, line in enumerate(lines, 2):
    parts = line.strip().split(',')
    if len(parts) >= 4:
        seq = parts[0]
        b_val = parts[1]
        c_val = parts[2]
        time_val = parts[3]

        ws.cell(i, 1, seq)
        ws.cell(i, 2, b_val)
        ws.cell(i, 3, c_val)
        ws.cell(i, 4, time_val)

